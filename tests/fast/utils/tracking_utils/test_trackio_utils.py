def _install_import_probe(monkeypatch, seen: dict):
    # Replace the fake module with an import hook so the test observes the
    # environment at the moment ``import trackio`` executes.
    import importlib.abc
    import importlib.util

    class _Loader(importlib.abc.Loader):
        def create_module(self, spec):
            return None

        def exec_module(self, module):
            seen["TRACKIO_DIR"] = os.environ.get("TRACKIO_DIR")
            module.init = lambda **kwargs: SimpleNamespace(name=kwargs.get("name"))

    class _Finder(importlib.abc.MetaPathFinder):
        def find_spec(self, fullname, path, target=None):
            if fullname == "trackio":
                return importlib.util.spec_from_loader(fullname, _Loader())
            return None

    monkeypatch.delitem(sys.modules, "trackio", raising=False)
    monkeypatch.setattr(sys, "meta_path", [_Finder(), *sys.meta_path])


@pytest.mark.parametrize("primary", [True, False])
def test_trackio_dir_is_exported_before_trackio_import(fake_trackio, monkeypatch, tmp_path, primary):
    # trackio resolves TRACKIO_DIR once at import time, so setting it after the
    # import would silently ignore --trackio-dir.
    seen = {}
    _install_import_probe(monkeypatch, seen)
    target = tmp_path / "trackio-logs"

    trackio_utils.init_trackio(_args(trackio_dir=str(target), trackio_run_name="r"), primary=primary)

    assert seen["TRACKIO_DIR"] == str(target)
    assert target.is_dir()


def test_trackio_dir_not_exported_for_remote(fake_trackio, monkeypatch, tmp_path):
    args = _args(trackio_dir=str(tmp_path / "ignored"), trackio_server_url="http://tracker:7860")

    trackio_utils.init_trackio(args, primary=True)

    assert "TRACKIO_DIR" not in os.environ
    assert not (tmp_path / "ignored").exists()


def test_log_and_finish_delegate(fake_trackio):
    trackio_utils.init_trackio(_args(), primary=True)

    trackio_utils.log_metrics({"train/loss": 0.5, "train/step": 3}, step=3)
    trackio_utils.finish()

    assert fake_trackio.log_calls == [({"train/loss": 0.5, "train/step": 3}, None)]
    # A run opened by trackio.init is closed through trackio.finish, which also
    # clears trackio's current-run context so its atexit hook does not finish twice.
    assert fake_trackio.finish_calls == 1
    assert fake_trackio.runs[0].finish_calls == 0
    assert trackio_utils._run is None


def test_backend_inactive_skips_log_and_finish(fake_trackio):
    from miles.utils.tracking_utils.base import TrackioBackend

    backend = TrackioBackend()
    args = _args(use_trackio=False)
    backend.init(args, primary=True)

    backend.log({"a": 1}, step=1)
    backend.finish()

    assert fake_trackio.log_calls == []
    assert fake_trackio.finish_calls == 0


def test_registry_lifecycle_through_tracking_manager(fake_trackio):
    from miles.utils.tracking_utils.base import TrackingManager, TrackioBackend

    manager = TrackingManager({"trackio": (TrackioBackend, "use_trackio")})
    args = _args(trackio_run_name="lifecycle")

    manager.init(args, primary=False)
    run = trackio_utils._run
    manager.log({"train/loss": 0.25}, step=7)
    manager.finish()

    assert fake_trackio.init_calls == []
    assert run.kwargs["name"] == "lifecycle"
    assert run.log_calls == [({"train/loss": 0.25}, None)]
    assert run.finish_calls == 1
