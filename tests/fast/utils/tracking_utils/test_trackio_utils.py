def test_secondary_local_opens_run_by_id_without_init(fake_trackio):
    # Actors and rollout_manager init with primary=False. resume="allow" only
    # matches a run that has already logged, so a name-based attach would mint a
    # second run id; the secondary opens the primary's run id directly instead.
    args = _args(trackio_run_name="from-primary", trackio_run_id="run-123")

    assert trackio_utils.init_trackio(args, primary=False) is True
    assert fake_trackio.init_calls == []
    run = trackio_utils._run
    assert run.kwargs == {
        "url": None,
        "project": "wproj",
        "client": None,
        "name": "from-primary",
        "run_id": "run-123",
        "group": "wgroup",
    }

    trackio_utils.log_metrics({"rollout/reward": 1.0})
    trackio_utils.finish()

    assert run.log_calls == [({"rollout/reward": 1.0}, None)]
    assert run.finish_calls == 1
    assert fake_trackio.finish_calls == 0


